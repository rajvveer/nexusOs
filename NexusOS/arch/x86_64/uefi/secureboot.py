#!/usr/bin/env python3
"""NexusOS Secure Boot key management and signing.

This tool owns the NexusOS secure-boot trust material:
  * a PK / KEK / db RSA-2048 key set (self-signed X.509) for UEFI Secure Boot enrollment, and
  * the "kernel" signing key whose PUBLIC modulus BOOTX64.EFI embeds (uefi/sb_pubkey.h) to verify KERNEL.BIN.

PRIVATE keys are written to a key directory OUTSIDE the source tree (env SECUREBOOT_KEYDIR, default
%USERPROFILE%\\.nexusos\\keys\\secureboot); only PUBLIC certificates (uefi/keys/*.crt,*.der) and the public modulus header
(uefi/sb_pubkey.h) live in the tree. Never commit the private keys.

Commands:
  gen    [KEYDIR]                generate PK/KEK/db + kernel keys, write certs + sb_pubkey.h
  sign   KERNEL.BIN  KERNEL.SIG  [KEYDIR]   RSA-2048/SHA-256 (PKCS#1 v1.5) detached signature over the kernel image

The loader verification (uefi/sb_verify.h) checks exactly this signature with the embedded modulus and e=65537.
"""
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TREE_KEYS = HERE / 'keys'
PUBKEY_HEADER = HERE / 'sb_pubkey.h'
DEFAULT_KEYDIR = Path(os.environ.get('SECUREBOOT_KEYDIR', str(Path.home() / '.nexusos' / 'keys' / 'secureboot')))


def _crypto():
    from cryptography.hazmat.primitives.asymmetric import rsa, padding
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography import x509
    from cryptography.x509.oid import NameOID
    import datetime
    return rsa, padding, hashes, serialization, x509, NameOID, datetime


def _self_signed(common_name):
    rsa, padding, hashes, serialization, x509, NameOID, datetime = _crypto()
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    subject = issuer = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, common_name),
                                  x509.NameAttribute(NameOID.ORGANIZATION_NAME, 'NexusOS')])
    now = datetime.datetime(2026, 1, 1, tzinfo=datetime.timezone.utc)
    cert = (x509.CertificateBuilder().subject_name(subject).issuer_name(issuer)
            .public_key(key.public_key()).serial_number(x509.random_serial_number())
            .not_valid_before(now).not_valid_after(now.replace(year=2046))
            .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
            .sign(key, hashes.SHA256()))
    return key, cert


def _write_key(keydir, name, key):
    _, _, _, serialization, _, _, _ = _crypto()
    path = keydir / (name + '_private.pem')
    path.write_bytes(key.private_bytes(serialization.Encoding.PEM,
                                       serialization.PrivateFormat.TraditionalOpenSSL,
                                       serialization.NoEncryption()))
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass


def _write_cert(name, cert):
    _, _, _, serialization, _, _, _ = _crypto()
    TREE_KEYS.mkdir(parents=True, exist_ok=True)
    (TREE_KEYS / (name + '.crt')).write_bytes(cert.public_bytes(serialization.Encoding.PEM))
    (TREE_KEYS / (name + '.der')).write_bytes(cert.public_bytes(serialization.Encoding.DER))


def _emit_header(kernel_key):
    modulus = kernel_key.public_key().public_numbers().n
    be = modulus.to_bytes(256, 'big')
    lines = ['/* AUTO-GENERATED by uefi/secureboot.py `gen`. The PUBLIC RSA-2048 modulus (big-endian, e=65537) that',
             ' * BOOTX64.EFI embeds to verify KERNEL.BIN. Public key material only - the private key lives in the',
             ' * secure-boot key directory (env SECUREBOOT_KEYDIR), never in the tree. */',
             '#ifndef NEXUS_SB_PUBKEY_H', '#define NEXUS_SB_PUBKEY_H', '#include <stdint.h>',
             'static const uint8_t sb_kernel_modulus[256] = {']
    for i in range(0, 256, 12):
        lines.append('    ' + ''.join(f'0x{b:02x},' for b in be[i:i+12]))
    lines.append('};')
    lines.append('#define SB_KERNEL_KEY_PRESENT 1')
    lines.append('#endif')
    PUBKEY_HEADER.write_text('\n'.join(lines) + '\n')


def gen(keydir):
    keydir = Path(keydir); keydir.mkdir(parents=True, exist_ok=True)
    names = {}
    for name, cn in (('PK', 'NexusOS Platform Key'), ('KEK', 'NexusOS Key Exchange Key'),
                     ('db', 'NexusOS Signature Database'), ('kernel', 'NexusOS Kernel Signing Key')):
        key, cert = _self_signed(cn)
        _write_key(keydir, name, key); _write_cert(name, cert); names[name] = key
    _emit_header(names['kernel'])
    print(f'[secureboot] keys in {keydir} (private, keep secret); certs in {TREE_KEYS}; header {PUBKEY_HEADER}')


def _load_key(keydir, name):
    _, _, _, serialization, _, _, _ = _crypto()
    data = (Path(keydir) / (name + '_private.pem')).read_bytes()
    return serialization.load_pem_private_key(data, password=None)


def sign(kernel_path, sig_path, keydir):
    rsa, padding, hashes, _, _, _, _ = _crypto()
    key = _load_key(keydir, 'kernel')
    signature = key.sign(Path(kernel_path).read_bytes(), padding.PKCS1v15(), hashes.SHA256())
    assert len(signature) == 256, len(signature)
    Path(sig_path).write_bytes(signature)
    print(f'[secureboot] signed {kernel_path} -> {sig_path} ({len(signature)} bytes, RSA-2048/SHA-256)')


def main(argv):
    if not argv:
        print(__doc__); return 2
    cmd = argv[0]
    if cmd == 'gen':
        gen(argv[1] if len(argv) > 1 else DEFAULT_KEYDIR)
    elif cmd == 'sign':
        if len(argv) < 3:
            print('usage: secureboot.py sign KERNEL.BIN KERNEL.SIG [KEYDIR]'); return 2
        sign(argv[1], argv[2], argv[3] if len(argv) > 3 else DEFAULT_KEYDIR)
    else:
        print(__doc__); return 2
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
