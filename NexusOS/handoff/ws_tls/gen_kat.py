"""Generate kernel/cryptokat.h: known-answer vectors for the in-VM `cryptotest`
command (SHA-2, HMAC, HKDF, AES, GCM, X25519, ECDSA P-256/P-384, RSA PKCS1/PSS,
and two real root certificates for the X.509 parser + self-signature check).
usage: python -I gen_kat.py <out_path>"""
import sys, hashlib, hmac, os, certifi
from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, rsa, padding, x25519
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature

out = []
def arr(name, b):
    out.append("static const uint8_t %s[%d] = {" % (name, max(len(b), 1)))
    if not b: out.append("    0,")
    for i in range(0, len(b), 16):
        out.append("    " + ",".join("0x%02x" % x for x in b[i:i+16]) + ",")
    out.append("};")

# --- hashes / mac / kdf ---
arr("KAT_SHA256_ABC", hashlib.sha256(b"abc").digest())
arr("KAT_SHA384_ABC", hashlib.sha384(b"abc").digest())
arr("KAT_SHA512_ABC", hashlib.sha512(b"abc").digest())
big = bytes(range(256)) * 5                      # 1280 bytes, multi-block
arr("KAT_BIG", big)
arr("KAT_SHA256_BIG", hashlib.sha256(big).digest())
arr("KAT_SHA384_BIG", hashlib.sha384(big).digest())
arr("KAT_HMAC_JEFE", hmac.new(b"Jefe", b"what do ya want for nothing?", hashlib.sha256).digest())
ikm = bytes([0x0b] * 22); salt = bytes(range(13)); info = bytes(range(0xf0, 0xfa))
okm = HKDF(algorithm=hashes.SHA256(), length=42, salt=salt, info=info).derive(ikm)
arr("KAT_HKDF_OKM", okm)

# --- AES / GCM ---
arr("KAT_AES_CT", bytes.fromhex("69c4e0d86a7b0430d8cdb78070b4c55a"))
key = bytes.fromhex("feffe9928665731c6d6a8f9467308308"); iv = bytes.fromhex("cafebabefacedbaddecaf888")
pt = bytes.fromhex("d9313225f88406e5a55909c5aff5269a86a7a9531534f7da2e4c303d8a318a721c3c0c95956809532fcf0e2449a6b525b16aedf5aa0de657ba637b39")
aad = bytes.fromhex("feedfacedeadbeeffeedfacedeadbeefabaddad2")
ct = AESGCM(key).encrypt(iv, pt, aad)
arr("KAT_GCM_KEY", key); arr("KAT_GCM_IV", iv); arr("KAT_GCM_PT", pt); arr("KAT_GCM_AAD", aad)
arr("KAT_GCM_CT", ct[:-16]); arr("KAT_GCM_TAG", ct[-16:])

# --- X25519 (RFC 7748 section 5.2 vector 1 + base-point) ---
arr("KAT_X_SCALAR", bytes.fromhex("a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4"))
arr("KAT_X_U", bytes.fromhex("e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c"))
arr("KAT_X_OUT", bytes.fromhex("c3da55379de9c6908e94ea4df28d084f32eccf03491c71f754b4075577a28552"))
priv = x25519.X25519PrivateKey.from_private_bytes(bytes(range(32)))
arr("KAT_X_BASE_PUB", priv.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw))

# --- ECDSA ---
msg = b"NexusOS TLS 1.3 known answer test message"
for name, curve, h in (("P256", ec.SECP256R1(), hashes.SHA256()), ("P384", ec.SECP384R1(), hashes.SHA384())):
    k = ec.generate_private_key(curve)
    sig = k.sign(msg, ec.ECDSA(h))
    pub = k.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
    arr("KAT_%s_PUB" % name, pub)
    arr("KAT_%s_SIG" % name, sig)        # DER SEQUENCE {r, s}
    spki = k.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    arr("KAT_%s_SPKI" % name, spki)
arr("KAT_MSG", msg)

# --- RSA 2048 ---
rk = rsa.generate_private_key(public_exponent=65537, key_size=2048)
n = rk.public_key().public_numbers().n.to_bytes(256, "big")
arr("KAT_RSA_N", n); arr("KAT_RSA_E", (65537).to_bytes(3, "big"))
arr("KAT_RSA_SIG_PKCS1", rk.sign(msg, padding.PKCS1v15(), hashes.SHA256()))
arr("KAT_RSA_SIG_PSS", rk.sign(msg, padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=32), hashes.SHA256()))
arr("KAT_RSA_SIG_PSS384", rk.sign(msg, padding.PSS(mgf=padding.MGF1(hashes.SHA384()), salt_length=48), hashes.SHA384()))
arr("KAT_RSA_SPKI", rk.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo))

# --- real root certificates (self-signed): RSA-4096/sha256 and P-384/sha384 ---
certs = x509.load_pem_x509_certificates(open(certifi.where(), "rb").read())
def find(cn):
    for c in certs:
        if "CN=" + cn in c.subject.rfc4514_string(): return c
    raise SystemExit("missing root " + cn)
arr("KAT_CERT_ISRG_X1", find("ISRG Root X1").public_bytes(serialization.Encoding.DER))
arr("KAT_CERT_ISRG_X2", find("ISRG Root X2").public_bytes(serialization.Encoding.DER))

hdr = ["/* AUTO-GENERATED by gen_kat.py — known-answer test vectors for `cryptotest`. */",
       "#ifndef CRYPTOKAT_H", "#define CRYPTOKAT_H", '#include "types.h"', ""]
open(sys.argv[1], "w", newline="\n").write("\n".join(hdr + out + ["", "#endif", ""]))
print("wrote", sys.argv[1], sum(1 for l in out if l.startswith("static")), "vectors")
