"""Generate NexusOS/kernel/roots.h (built-in TLS root store) from certifi's CA bundle.

Each root is stored as: friendly name, DER-encoded subject Name (for issuer
matching), DER-encoded SubjectPublicKeyInfo (parsed at run time by x509.c).
usage: python -I gen_roots.py <out_path>
"""
import sys, certifi
from cryptography import x509
from cryptography.hazmat.primitives import serialization

WANTED = [
    # (friendly name, subject CN or distinguishing substring of the RFC4514 subject)
    ("ISRG Root X1", "CN=ISRG Root X1"),
    ("ISRG Root X2", "CN=ISRG Root X2"),
    ("DigiCert Global Root G2", "CN=DigiCert Global Root G2"),
    ("DigiCert Global Root G3", "CN=DigiCert Global Root G3"),
    ("DigiCert Global Root CA", "CN=DigiCert Global Root CA"),
    ("DigiCert High Assurance EV Root CA", "CN=DigiCert High Assurance EV Root CA"),
    ("GlobalSign Root CA - R3", "OU=GlobalSign Root CA - R3"),
    ("GlobalSign Root CA", "OU=Root CA,O=GlobalSign nv-sa,C=BE"),
    ("GTS Root R1", "CN=GTS Root R1"),
    ("GTS Root R4", "CN=GTS Root R4"),
    ("Amazon Root CA 1", "CN=Amazon Root CA 1"),
    ("Baltimore CyberTrust Root", "CN=Baltimore CyberTrust Root"),
    ("USERTrust RSA Certification Authority", "CN=USERTrust RSA Certification Authority"),
    ("USERTrust ECC Certification Authority", "CN=USERTrust ECC Certification Authority"),
    ("COMODO ECC Certification Authority", "CN=COMODO ECC Certification Authority"),
    ("AAA Certificate Services", "CN=AAA Certificate Services"),
    ("SSL.com TLS ECC Root CA 2022", "CN=SSL.com TLS ECC Root CA 2022"),
    ("SSL.com TLS RSA Root CA 2022", "CN=SSL.com TLS RSA Root CA 2022"),
    ("Microsoft RSA Root Certificate Authority 2017", "CN=Microsoft RSA Root Certificate Authority 2017"),
    ("Sectigo Public Server Authentication Root E46", "CN=Sectigo Public Server Authentication Root E46"),
]

def main(out):
    pem = open(certifi.where(), "rb").read()
    certs = x509.load_pem_x509_certificates(pem)
    by_subject = {c.subject.rfc4514_string(): c for c in certs}
    chosen = []
    for name, key in WANTED:
        hits = [c for s, c in by_subject.items() if key in s]
        if not hits:
            print("WARN: not found:", name); continue
        if len(hits) > 1:
            print("WARN: ambiguous:", name, [h.subject.rfc4514_string() for h in hits])
        c = hits[0]
        subj = c.subject.public_bytes()
        spki = c.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
        chosen.append((name, subj, spki, c.subject.rfc4514_string()))
    lines = ["/* AUTO-GENERATED by gen_roots.py from certifi %s — do not edit.\n" % certifi.__version__,
             " * NexusOS built-in TLS root store: subject Name DER + SubjectPublicKeyInfo DER. */",
             "#ifndef ROOTS_H", "#define ROOTS_H", '#include "types.h"', "",
             "typedef struct {", "    const char*    name;", "    const uint8_t* subject;  uint16_t subject_len;",
             "    const uint8_t* spki;     uint16_t spki_len;", "} root_cert_t;", ""]
    total = 0
    def arr(nm, b):
        rows = []
        for i in range(0, len(b), 16):
            rows.append("    " + ",".join("0x%02x" % x for x in b[i:i+16]) + ",")
        return ["static const uint8_t %s[%d] = {" % (nm, len(b))] + rows + ["};"]
    for i, (name, subj, spki, full) in enumerate(chosen):
        lines.append("/* %s */" % full)
        lines += arr("root%d_subj" % i, subj)
        lines += arr("root%d_spki" % i, spki)
        total += len(subj) + len(spki)
    lines += ["", "static const root_cert_t ROOT_STORE[] = {"]
    for i, (name, subj, spki, full) in enumerate(chosen):
        lines.append('    { "%s", root%d_subj, %d, root%d_spki, %d },' % (name, i, len(subj), i, len(spki)))
    lines += ["};", "#define ROOT_STORE_COUNT %d" % len(chosen), "", "#endif /* ROOTS_H */", ""]
    open(out, "w", newline="\n").write("\n".join(lines))
    print("wrote", out, "roots:", len(chosen), "payload bytes:", total)

if __name__ == "__main__":
    main(sys.argv[1])
