"""Convert /proc/asound codec dumps (alsa-info.sh "Codec:" sections, tests/fixtures/hda/*.txt) into a C header of
simulated codecs for tests/hda_codec_test.c: per node the widget capabilities, pin capabilities and default
configuration, amplifier capabilities, PCM capabilities, connection list and DP-MST device count; per codec the vendor,
subsystem and revision ids and the audio function group defaults.

    python -I tests/hda_dump_to_c.py <output.h> <dump.txt> ...      (also: --summary <dump.txt> ...)"""
import pathlib
import re
import sys

def amp(text):
    m = re.search(r'ofs=0x([0-9a-f]+), nsteps=0x([0-9a-f]+), stepsize=0x([0-9a-f]+), mute=(\d)', text)
    if not m:
        return 0
    return int(m.group(1), 16) | int(m.group(2), 16) << 8 | int(m.group(3), 16) << 16 | int(m.group(4)) << 31

def parse(path):
    lines = pathlib.Path(path).read_text().splitlines()
    codec = {'name': pathlib.Path(path).stem, 'nodes': {}, 'afg_pcm': 0, 'afg_in': 0, 'afg_out': 0}
    node = None; section = None; pending_conn = 0
    for raw in lines:
        if raw.startswith('#'):
            continue
        line = raw.strip()
        if raw.startswith('Codec:'):
            codec['title'] = raw.split(':', 1)[1].strip()
        elif raw.startswith('Vendor Id:'):
            codec['vendor'] = int(raw.split(':')[1], 16)
        elif raw.startswith('Subsystem Id:'):
            codec['subsystem'] = int(raw.split(':')[1], 16)
        elif raw.startswith('Revision Id:'):
            codec['revision'] = int(raw.split(':')[1], 16)
        elif raw.startswith('Default PCM:'):
            section = 'afg_pcm'
        elif raw.startswith('Default Amp-In caps:'):
            codec['afg_in'] = amp(raw)
        elif raw.startswith('Default Amp-Out caps:'):
            codec['afg_out'] = amp(raw)
        elif raw.startswith('Node 0x'):
            m = re.match(r'Node 0x([0-9a-f]+) \[([^\]]+)\] wcaps 0x([0-9a-f]+)', raw)
            nid = int(m.group(1), 16)
            node = {'nid': nid, 'type': m.group(2), 'wcaps': int(m.group(3), 16), 'pincaps': 0, 'config': 0,
                    'amp_in': 0, 'amp_out': 0, 'pcm': 0, 'conn': [], 'devices': 0}
            codec['nodes'][nid] = node; section = None; pending_conn = 0
        elif node is not None:
            if pending_conn:
                node['conn'] += [int(x.rstrip('*'), 16) for x in line.split()]
                pending_conn = 0
            elif line.startswith('Pincap 0x'):
                node['pincaps'] = int(line.split()[1].rstrip(':'), 16)
            elif line.startswith('Pin Default 0x'):
                node['config'] = int(line.split()[2].rstrip(':'), 16)
            elif line.startswith('Amp-In caps:'):
                node['amp_in'] = amp(line)
            elif line.startswith('Amp-Out caps:'):
                node['amp_out'] = amp(line)
            elif line.startswith('PCM:'):
                section = 'pcm'
            elif line.startswith('Connection:'):
                if int(line.split(':')[1]) > 0:
                    pending_conn = 1
            elif line.startswith('Devices:'):
                node['devices'] = int(line.split(':')[1])
        if section and 'rates [0x' in line:
            value = int(re.search(r'rates \[0x([0-9a-f]+)\]', line).group(1), 16)
            if section == 'afg_pcm': codec['afg_pcm'] = (codec['afg_pcm'] & ~0xFFF) | value
            else: node['pcm'] = (node['pcm'] & ~0xFFF) | value
        if section and 'bits [0x' in line:
            value = int(re.search(r'bits \[0x([0-9a-f]+)\]', line).group(1), 16)
            if section == 'afg_pcm': codec['afg_pcm'] |= value << 16
            else: node['pcm'] |= value << 16
            section = None
    return codec

def c_name(stem):
    return re.sub(r'[^A-Za-z0-9]', '_', stem)

def emit(out, paths):
    text = ['/* Generated by tests/hda_dump_to_c.py from tests/fixtures/hda (sources in each file header). */',
            'struct dump_node { uint16_t nid; uint32_t wcaps, pincaps, config, amp_in, amp_out, pcm; uint8_t devices, conns; uint16_t conn[16]; };',
            'struct dump_codec { const char* name; uint32_t vendor, subsystem, revision, afg_pcm, afg_in, afg_out; unsigned first, count, nodes; const struct dump_node* node; };']
    entries = []
    for path in paths:
        codec = parse(path)
        name = c_name(codec['name'])
        nids = sorted(codec['nodes'])
        rows = []
        for nid in nids:
            n = codec['nodes'][nid]
            assert len(n['conn']) <= 16, (path, nid)
            conn = ', '.join(f'0x{c:02x}' for c in n['conn']) or '0'
            rows.append(f'    {{0x{nid:02x}, 0x{n["wcaps"]:08x}, 0x{n["pincaps"]:08x}, 0x{n["config"]:08x}, 0x{n["amp_in"]:08x}, '
                        f'0x{n["amp_out"]:08x}, 0x{n["pcm"]:08x}, {max(0, n["devices"] - 1) if n["devices"] else 0}, {len(n["conn"])}, {{{conn}}}}},')
        text.append(f'static const struct dump_node {name}_nodes[] = {{')
        text += rows
        text.append('};')
        entries.append(f'    {{"{codec["name"]}", 0x{codec["vendor"]:08x}, 0x{codec["subsystem"]:08x}, 0x{codec["revision"]:08x}, '
                       f'0x{codec["afg_pcm"]:08x}, 0x{codec["afg_in"]:08x}, 0x{codec["afg_out"]:08x}, 0x{nids[0]:02x}, {nids[-1] - nids[0] + 1}, '
                       f'{len(nids)}, {name}_nodes}},')
    text.append('static const struct dump_codec dumps[] = {')
    text += entries
    text.append('};')
    pathlib.Path(out).write_text('\n'.join(text) + '\n', newline='\n')

def summary(paths):
    for path in paths:
        codec = parse(path)
        print(f"== {codec['name']}: {codec['title']} vendor {codec['vendor']:08x} rev {codec['revision']:08x}")
        for nid, n in sorted(codec['nodes'].items()):
            if n['type'] == 'Pin Complex' or n['devices']:
                cfg = n['config']
                print(f"  pin 0x{nid:02x} cfg {cfg:08x} conn {cfg >> 30} loc {(cfg >> 24) & 0x3f:02x} dev {(cfg >> 20) & 15:x} "
                      f"misc {(cfg >> 8) & 15:x} pincap {n['pincaps']:08x} devices {n['devices']} -> {[hex(c) for c in n['conn']]}")

if __name__ == '__main__':
    if sys.argv[1] == '--summary':
        summary(sys.argv[2:])
    else:
        emit(sys.argv[1], sys.argv[2:])
