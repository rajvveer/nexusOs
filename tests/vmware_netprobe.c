/* /sbin/init for tests/test_vmware.py --internet: waits for the DHCP-generated /etc/resolv.conf, resolves
   example.com with glibc and fetches its front page over HTTP. */
#include <arpa/inet.h>
#include <netdb.h>
#include <stdio.h>
#include <string.h>
#include <sys/socket.h>
#include <time.h>
#include <unistd.h>

int main(void) {
    printf("NETPROBE start\n");
    for (int i = 0; i < 100; i++) {
        FILE* f = fopen("/etc/resolv.conf", "r"); char line[256]; int generated = 0;
        if (f) { while (fgets(line, sizeof line, f)) if (strstr(line, "Generated by the NexusOS kernel")) generated = 1; fclose(f); }
        if (generated) break;
        struct timespec t = {0, 100000000}; nanosleep(&t, NULL);
    }
    FILE* f = fopen("/etc/resolv.conf", "r"); char line[256];
    if (f) { while (fgets(line, sizeof line, f)) printf("NETPROBE resolv: %s", line); fclose(f); }
    struct addrinfo hints = {0}, *result = NULL; hints.ai_family = AF_INET; hints.ai_socktype = SOCK_STREAM;
    int error = getaddrinfo("example.com", "80", &hints, &result);
    if (error) { printf("NETPROBE dns FAIL %s\nNETPROBE done\n", gai_strerror(error)); return 1; }
    char address[32]; inet_ntop(AF_INET, &((struct sockaddr_in*)result->ai_addr)->sin_addr, address, sizeof address);
    printf("NETPROBE dns example.com -> %s\n", address);
    int fd = socket(AF_INET, SOCK_STREAM, 0);
    if (connect(fd, result->ai_addr, result->ai_addrlen)) { printf("NETPROBE connect FAIL\nNETPROBE done\n"); return 1; }
    const char request[] = "GET / HTTP/1.1\r\nHost: example.com\r\nConnection: close\r\n\r\n";
    if (write(fd, request, sizeof request - 1) != (ssize_t)(sizeof request - 1)) { printf("NETPROBE write FAIL\nNETPROBE done\n"); return 1; }
    char reply[512] = {0}; ssize_t n = read(fd, reply, sizeof reply - 1);
    char* end = strstr(reply, "\r\n"); if (end) *end = 0;
    printf("NETPROBE http %zd bytes: %s\n", n, reply);
    close(fd); freeaddrinfo(result);
    printf("NETPROBE done\n");
    return 0;
}
